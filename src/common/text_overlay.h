  GLuint program = 0;
  GLuint vao = 0;
  GLuint vbo = 0;
  int loc_proj = -1;
  int loc_color = -1;
  int loc_tex = -1;
  float win_w = 0;
  float win_h = 0;
  float proj[16] = {};

  void init(int w, int h) {
    win_w = static_cast<float>(w);
    win_h = static_cast<float>(h);
    makeProjection();
    createFontTexture();
    compileShaders();

    glGenVertexArrays(1, &vao);
    glBindVertexArray(vao);
    glGenBuffers(1, &vbo);
    glBindBuffer(GL_ARRAY_BUFFER, vbo);
    glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE, sizeof(float) * 4,
                          reinterpret_cast<void *>(0));
    glEnableVertexAttribArray(0);
    glVertexAttribPointer(1, 2, GL_FLOAT, GL_FALSE, sizeof(float) * 4,
                          reinterpret_cast<void *>(sizeof(float) * 2));
    glEnableVertexAttribArray(1);
    glBindVertexArray(0);
  }

  void destroy() {
    if (program)
      glDeleteProgram(program);
    if (font_tex)
      glDeleteTextures(1, &font_tex);
    if (vbo)
      glDeleteBuffers(1, &vbo);
    if (vao)
      glDeleteVertexArrays(1, &vao);
    program = 0;
    font_tex = 0;
    vbo = 0;
    vao = 0;
  }

  void resize(int w, int h) {
    win_w = static_cast<float>(w);
    win_h = static_cast<float>(h);
    makeProjection();
  }

  void draw(float x, float y, const char *text, float scale = 1.0f,
            float r = 1.0f, float g = 1.0f, float b = 1.0f) {
    int len = static_cast<int>(std::strlen(text));
    if (len == 0)
      return;

    std::vector<float> verts;
    verts.reserve(static_cast<size_t>(len) * 24);

    float char_w = 8.0f * scale;
    float char_h = 8.0f * scale;

    for (int i = 0; i < len; i++) {
      unsigned char c = static_cast<unsigned char>(text[i]);
      if (c >= 128)
        c = 0;

      float u0 = static_cast<float>(c % 16) / 16.0f;
      float v0 = static_cast<float>(c / 16) / 8.0f;
      float u1 = u0 + 1.0f / 16.0f;
      float v1 = v0 + 1.0f / 8.0f;

      float x0 = x + static_cast<float>(i) * char_w;
      float y0 = y;
      float x1 = x0 + char_w;
      float y1 = y0 + char_h;

      float v[] = {
          x0, y0, u0, v0, x1, y0, u1, v0, x1, y1, u1, v1,
          x0, y0, u0, v0, x1, y1, u1, v1, x0, y1, u0, v1,
      };
      verts.insert(verts.end(), v, v + 24);
    }

    glEnable(GL_BLEND);
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);
    glDisable(GL_DEPTH_TEST);

    glUseProgram(program);
    glUniformMatrix4fv(loc_proj, 1, GL_FALSE, proj);
    glUniform3f(loc_color, r, g, b);

    glActiveTexture(GL_TEXTURE0);
    glBindTexture(GL_TEXTURE_2D, font_tex);
    glUniform1i(loc_tex, 0);

    glBindVertexArray(vao);
    glBindBuffer(GL_ARRAY_BUFFER, vbo);
    glBufferData(GL_ARRAY_BUFFER,
                 static_cast<GLsizeiptr>(verts.size() * sizeof(float)),
                 verts.data(), GL_STREAM_DRAW);
    glDrawArrays(GL_TRIANGLES, 0, len * 6);
    glBindVertexArray(0);
    glUseProgram(0);

    glDisable(GL_BLEND);
  }

