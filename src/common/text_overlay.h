  void compileShaders() {
    const char *vs_src = R"(
            #version 330 core
            layout(location = 0) in vec2 a_pos;
            layout(location = 1) in vec2 a_uv;
            uniform mat4 u_proj;
            out vec2 v_uv;
            void main() {
                gl_Position = u_proj * vec4(a_pos, 0.0, 1.0);
                v_uv = a_uv;
            }
        )";

    const char *fs_src = R"(
            #version 330 core
            in vec2 v_uv;
            uniform sampler2D u_tex;
            uniform vec3 u_color;
            out vec4 fragColor;
            void main() {
                float a = texture(u_tex, v_uv).r;
                fragColor = vec4(u_color, a);
            }
        )";

    GLuint vs = glCreateShader(GL_VERTEX_SHADER);
    glShaderSource(vs, 1, &vs_src, nullptr);
    glCompileShader(vs);

    GLuint fs = glCreateShader(GL_FRAGMENT_SHADER);
    glShaderSource(fs, 1, &fs_src, nullptr);
    glCompileShader(fs);

    program = glCreateProgram();
    glAttachShader(program, vs);
    glAttachShader(program, fs);
    glLinkProgram(program);

    GLint ok;
    glGetProgramiv(program, GL_LINK_STATUS, &ok);
    if (!ok) {
      char log[1024];
      glGetProgramInfoLog(program, sizeof(log), nullptr, log);
      std::fprintf(stderr, "TextOverlay shader link error: %s\n", log);
    }

    glDeleteShader(vs);
    glDeleteShader(fs);

    loc_proj = glGetUniformLocation(program, "u_proj");
    loc_color = glGetUniformLocation(program, "u_color");
    loc_tex = glGetUniformLocation(program, "u_tex");
  }
